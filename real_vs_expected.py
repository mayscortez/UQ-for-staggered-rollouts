from helper import sbm_2level_prob_matrix, SBM, complete_staggered_rollout_two_stage, complete_coeffs, homophily_effects, pom_ugander_yin, clustering_metrics
from joblib import Parallel, delayed 
import pickle
import time
import numpy as np

startTime = time.time()
rng = np.random.default_rng(2727)

# Parameters
betas = [2]  # Polynomial degree for outcome model
budgets = [0.025, 0.125, 0.25]  # Treatment budget proportion p [0.025, 0.05, 0.1, 0.125, 0.15, 0.2, 0.25]
qs = ["p", "2p", "1"] # 2nd stage treatment prob options: "p" means q = p, "2p" means q = 2p, "1" means q = 1
r = 100  # Number of randomized design replications 

# Network Parameters
sizes = [10000] # graph sizes i.e population sizes
clusterSize = 10 # number of units per fine cluster 
clusterSizeBig = 100 # number of units per coarse cluster
# TODO: would need to make these probabilities a function of n to keep a constant degree across graphs
p_cross = 0 # probability of edge between two units of different coarse clusters
p_out = 0.01 # probability of edge between two units of different fine clusters but same coarse cluster
p_in = 0.5 # probability of edge between two units of same fine cluster in same coarse cluster

##############################################
def pi_estimate_tte_two_stage_complete(Y, nu, k, beta):
    '''
    Computes TTE estimate from polynomial interpolation.
    :param Y: Potential outcomes, shape (beta+1, r, n)
    :param nu: Expected size of subset U
    :param k: Treatment budget (in units)
    :return: Estimated treatment effect
    '''
    H = complete_coeffs(beta, nu, k)  # Compute polynomial coefficients
    return 1 / nu * H @ np.sum(Y, axis=-1)

def pi_estimate_tte_two_stage_complete_nu_list(Y, nu_list, k, beta):
    '''
    Computes TTE estimate from polynomial interpolation.
    :param Y: Potential outcomes, shape (beta+1, r, n)
    :param nu: Numpy array of sizes of subset U (one per repetition r)
    :param k: Treatment budget (in units)
    :return: Estimated treatment effect
    '''
    H_list = [complete_coeffs(beta, nu, k) for nu in nu_list]  # Compute polynomial coefficients
    vec_sum = [H @ np.sum(Y[:,idx,:], axis=-1) for idx,H in enumerate(H_list)]
    return np.divide(vec_sum, nu_list, out=np.zeros(len(nu_list)), where=(nu_list != 0)) # this line was generated by Claude Sonnet 5.5

# Function to estimate TTE in a two-stage experiment
def estimate_two_stage(n,fY,Cl,r,nu_str,K,beta,p):
    tte_hat = []
    e_tte_hat_given_u = []

    if nu_str == "p":
        nu = n
    elif nu_str == "2p":
        nu = n//2
    elif nu_str == "1":
        nu = int(n*p)
    else:
        print(f"ERROR: unexpected nu_str value {nu_str} not implemented")

    # Generate treatment and control assignments, compute potential outcomes
    Z,U = complete_staggered_rollout_two_stage(n, Cl, nu, K, r) 
    Y = fY(Z)

    # Compute TTE estimates
    tte_hat = np.append(tte_hat,pi_estimate_tte_two_stage_complete(Y,nu,int(n*p),beta))

    # Compute conditional expectations
    e_tte_hat_given_u = np.append(e_tte_hat_given_u, (1/nu)*np.sum(fY(U) - fY(np.zeros(n)),axis=1))

    return (nu_str, nu, tte_hat, e_tte_hat_given_u, Y, U)

def estimate_two_stage_clusters(Y,Cl,q,beta,clusterSizeBig,p):
    tte_hat = []
    nu = int(clusterSizeBig * p / q) # recomputed

    # Get the outcomes Y only from units in Cl; Y shape = (beta+1, r, n)
    Y_cl = Y[:,:,Cl]

    # Compute TTE estimates
    tte_hat = np.append(tte_hat,pi_estimate_tte_two_stage_complete(Y_cl,nu,int(clusterSizeBig*p),beta))

    return tte_hat

def estimate_two_stage_clusters_realized(Y,U,Cl,beta,clusterSizeBig,p):
    tte_hat = []
    realized_nu = np.sum(U[:,Cl],axis=1)

    # Get the outcomes Y only from units in Cl; Y shape = (beta+1, r, n)
    Y_cl = Y[:,:,Cl]

    # Compute TTE estimates pi_estimate_tte_two_stage_complete_nu_list(Y, nu_list, k, beta)
    tte_hat = np.append(tte_hat,pi_estimate_tte_two_stage_complete_nu_list(Y_cl,realized_nu,int(clusterSizeBig*p),beta))

    return tte_hat

# Initliaizing dictionaries that hold the results
TTE_true_list = {b: {n: 0 for n in sizes} for b in betas}

# Store TTE estimates from 2-stage rollout paper
# e.g. TTE_hat_dict[b][n][p][q] holds a tte estimate for beta = b, population size = n, treatment budget p, and stage-2 treatment probability q
TTE_hat_dict = {b: {n: {p: {q:[] for q in qs} for p in budgets} for n in sizes} for b in betas}
Bias_dict = {b: {n: {p: {q:[] for q in qs} for p in budgets} for n in sizes} for b in betas}

# Store cluster-level TTE estimates using expected values
# e.g. TTE_hat_dict_Cl[b][n][p][q] holds...
TTE_hat_dict_Cl = {b: {n: {p: {q:[] for q in qs} for p in budgets} for n in sizes} for b in betas}
Bias_dict_Cl = {b: {n: {p: {q:[] for q in qs} for p in budgets} for n in sizes} for b in betas}

# Store cluster-level TTE estimates using realized values
# e.g. TTE_hat_dict_Cl[b][n][p][q] holds...
TTE_hat_dict_Cl_real = {b: {n: {p: {q:[] for q in qs} for p in budgets} for n in sizes} for b in betas}
Bias_dict_Cl_real = {b: {n: {p: {q:[] for q in qs} for p in budgets} for n in sizes} for b in betas}

for beta in betas:
    for n in sizes:
        # Graph parameters
        clusterNum = n//clusterSize # number of fine clusters (total)
        clusterNumBig = n//clusterSizeBig # number of coarse clusters (total) 
        probs = sbm_2level_prob_matrix(p_in, p_out, p_cross, clusterNum, clusterNumBig) # create the edge probability matrix

        # Build the graph
        A = SBM(clusterSize, probs, self_loops = True)
        h = homophily_effects(A, numComponents=clusterNumBig)
        fY = pom_ugander_yin(A,h,beta)
        TTE_true = np.sum(fY(np.ones(n))-fY(np.zeros(n)))/n
        TTE_true_list[beta][n] = TTE_true

        # Define the FINE clustering 
        Cl_fine = []
        add = 0
        for k in range(clusterNum):
            Cl_fine.append(list(range(k+add,k+add+clusterSize)))
            add+=clusterSize-1

        # Define the COARSE clustering
        Cl_coarse = []
        add = 0
        for k in range(clusterNumBig):
            Cl_coarse.append(list(range(k+add,k+add+clusterSizeBig)))
            add+=clusterSizeBig-1

        for p in budgets: # (nu_str, tte_hat, e_tte_hat_given_u, Y, U)
            K = np.linspace(0,int(n*p),beta+1,dtype=int)
            # TODO: test if parallelization here actually speeds up computation time
            for (nu_str,nu,TTE_hat,E_given_U,Y,U) in Parallel(n_jobs=3, verbose=5)(delayed(lambda nu_str : estimate_two_stage(n,fY,Cl_fine,r,nu_str,K,beta,p))(nu_str) for nu_str in qs): # type: ignore[misc]
                q = (n*p)/nu

                TTE_hat_dict[beta][n][p][nu_str].append(TTE_hat) 
                Bias_dict[beta][n][p][nu_str].append(TTE_hat - TTE_true)

                # Compute cluster-level estimates using expected counts; this part was generated by Claude Sonnet 5.5
                coarse_estimates = np.array(Parallel(n_jobs=-2, verbose=5)(delayed(estimate_two_stage_clusters)(Y, Cl, q, beta, clusterSizeBig, p) for Cl in Cl_coarse))
                TTE_hat_dict_Cl[beta][n][p][nu_str].append(coarse_estimates)
                Bias_dict_Cl[beta][n][p][nu_str].append(coarse_estimates - TTE_true)

                # Compute cluster-level estimates using realized counts
                coarse_estimates_real = np.array(Parallel(n_jobs=-2, verbose=5)(delayed(estimate_two_stage_clusters_realized)(Y, U, Cl, beta, clusterSizeBig, p) for Cl in Cl_coarse))
                TTE_hat_dict_Cl_real[beta][n][p][nu_str].append(coarse_estimates_real)
                Bias_dict_Cl_real[beta][n][p][nu_str].append(coarse_estimates_real - TTE_true)


data = {"TTE_true" : TTE_true_list,
        "pe1_TTE_hat": TTE_hat_dict,
        "pe1_bias": Bias_dict,
        "cluster_TTE_hat": TTE_hat_dict_Cl,
        "cluster_bias": Bias_dict_Cl,
        "cluster_TTE_hat_real": TTE_hat_dict_Cl_real,
        "cluster_bias_real": Bias_dict_Cl_real}
file = open("real_vs_exp.pkl", "wb")
pickle.dump((data), file)
file.close()

executionTime = (time.time() - startTime)
print('Total runtime in minutes: {}'.format(executionTime/60)) 
    
        